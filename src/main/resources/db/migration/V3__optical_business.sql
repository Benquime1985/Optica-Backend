CREATE TABLE patients (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 first_name VARCHAR(100) NOT NULL, last_name VARCHAR(200) NOT NULL,
 birth_date DATE, phone VARCHAR(30), email VARCHAR(254), notes VARCHAR(4000),
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE products (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 sku VARCHAR(80) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL,
 category VARCHAR(30) NOT NULL CHECK(category IN ('FRAME','LENS','CONTACT_LENS','ACCESSORY')),
 price NUMERIC(12,2) NOT NULL CHECK(price >= 0),
 stock INTEGER NOT NULL CHECK(stock >= 0), active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE prescriptions (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES patients(id),
 optometrist_id BIGINT NOT NULL REFERENCES users(id),
 examined_on DATE NOT NULL, right_sphere NUMERIC(5,2), right_cylinder NUMERIC(5,2),
 right_axis INTEGER CHECK(right_axis BETWEEN 0 AND 180),
 left_sphere NUMERIC(5,2), left_cylinder NUMERIC(5,2),
 left_axis INTEGER CHECK(left_axis BETWEEN 0 AND 180),
 addition NUMERIC(4,2), pupillary_distance NUMERIC(5,2), notes VARCHAR(4000)
);
CREATE TABLE appointments (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES patients(id),
 optometrist_id BIGINT NOT NULL REFERENCES users(id),
 starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED' CHECK(status IN ('SCHEDULED','COMPLETED','CANCELLED')),
 notes VARCHAR(1000), CHECK(ends_at > starts_at)
);
CREATE INDEX appointments_schedule ON appointments(optometrist_id, starts_at);
CREATE TABLE sales (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES patients(id), seller_id BIGINT NOT NULL REFERENCES users(id),
 total NUMERIC(12,2) NOT NULL CHECK(total >= 0), paid NUMERIC(12,2) NOT NULL CHECK(paid >= 0 AND paid <= total),
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','DELIVERED','CANCELLED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE sale_items (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 sale_id BIGINT NOT NULL REFERENCES sales(id), product_id BIGINT NOT NULL REFERENCES products(id),
 quantity INTEGER NOT NULL CHECK(quantity > 0), unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price >= 0)
);
CREATE TABLE payments (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 sale_id BIGINT NOT NULL REFERENCES sales(id), amount NUMERIC(12,2) NOT NULL CHECK(amount > 0),
 received_by BIGINT NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE stock_movements (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL REFERENCES products(id), quantity INTEGER NOT NULL CHECK(quantity <> 0),
 reason VARCHAR(200) NOT NULL, user_id BIGINT NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX users_email_lower ON users(lower(email));

